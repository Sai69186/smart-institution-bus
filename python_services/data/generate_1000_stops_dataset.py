# 3. GENERATE 1000 STOPS WITH REALISTIC GPS COORDINATES
# ══════════════════════════════════════════════════════════════════════════════

def haversine_km(lat1, lng1, lat2, lng2):
    R = 6371.0
    dlat = math.radians(lat2 - lat1)
    dlng = math.radians(lng2 - lng1)
    a = math.sin(dlat/2)**2 + math.cos(math.radians(lat1))*math.cos(math.radians(lat2))*math.sin(dlng/2)**2
    return R * 2 * math.asin(math.sqrt(max(0.0, a)))


def offset_coords(base_lat, base_lng, dist_km, bearing_deg):
    """Move (base_lat, base_lng) by dist_km in bearing_deg direction."""
    R     = 6371.0
    b     = math.radians(bearing_deg)
    d     = dist_km / R
    lat1  = math.radians(base_lat)
    lng1  = math.radians(base_lng)
    lat2  = math.asin(math.sin(lat1)*math.cos(d) + math.cos(lat1)*math.sin(d)*math.cos(b))
    lng2  = lng1 + math.atan2(math.sin(b)*math.sin(d)*math.cos(lat1),
                              math.cos(d) - math.sin(lat1)*math.sin(lat2))
    return round(math.degrees(lat2), 6), round(math.degrees(lng2), 6)


stops_data = []   # list of dicts
used_names = set()

TARGET_STOPS = 1000
stops_per_inst = TARGET_STOPS // len(INSTITUTIONS)  # ~66 per institution

for inst_name, campus_lat, campus_lng, city, n_buses in INSTITUTIONS:
    inst_id     = f"AP_INST_{inst_name.replace(' ','_')}"
    city_areas  = AREA_PREFIXES_BY_CITY.get(city, AREA_PREFIXES_BY_CITY["Vijayawada"])

    n_stops_this_inst = stops_per_inst + (1 if len(stops_data) + stops_per_inst < TARGET_STOPS else 0)

    # Generate stops along radial corridors (8 directions from campus)
    bearings = [0, 45, 90, 135, 180, 225, 270, 315]
    distances = [1.0, 2.5, 4.0, 6.0, 8.5, 12.0, 16.0, 22.0, 28.0]

    stop_count = 0
    for bearing in bearings:
        for dist in distances:
            if stop_count >= n_stops_this_inst:
                break

            # Slight randomisation so stops don't fall exactly on radials
            actual_dist    = dist * np.random.uniform(0.85, 1.15)
            actual_bearing = bearing + np.random.uniform(-15, 15)

            slat, slng = offset_coords(campus_lat, campus_lng, actual_dist, actual_bearing)

            # Pick area name
            area = city_areas[stop_count % len(city_areas)]
            suffix = random.choice(STOP_SUFFIXES)
            candidate = f"{area} {suffix}"

            # Ensure unique name (append number if needed)
            if candidate in used_names:
                candidate = f"{area} {suffix} {stop_count}"
            used_names.add(candidate)

            road_type    = np.random.choice(ROAD_TYPES, p=ROAD_TYPE_WEIGHTS)
            dist_to_camp = round(haversine_km(slat, slng, campus_lat, campus_lng), 3)

            stops_data.append({
                "stop":             candidate,
                "stop_lat":         slat,
                "stop_lng":         slng,
                "stop_distance_km": dist_to_camp,
                "road_type":        road_type,
                "institution_id":   inst_id,
                "campus_lat":       campus_lat,
                "campus_lng":       campus_lng,
                "city":             city,
            })
            stop_count += 1

        if stop_count >= n_stops_this_inst:
            break

print(f"Generated {len(stops_data)} stops")

